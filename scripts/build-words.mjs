// Generates js/words.js from the raw list files in scripts/raw/.
// answers.txt  - original answer list, original order (puzzle #0 = "cigar")
// allowed.txt  - original extra valid guesses
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => readFileSync(join(here, 'raw', f), 'utf8')
  .split(/\r?\n/).map((w) => w.trim()).filter(Boolean);

const solutions = read('answers.txt');
const allowed = read('allowed.txt');

// One word per 10 in a row keeps the file compact but still diffable.
const pack = (list) => {
  const lines = [];
  for (let i = 0; i < list.length; i += 10) {
    lines.push('  ' + list.slice(i, i + 10).map((w) => `'${w}'`).join(','));
  }
  return lines.join(',\n');
};

const out = `// Generated by scripts/build-words.mjs. Do not edit by hand.
export const SOLUTIONS = [
${pack(solutions)}
];

export const ALLOWED = [
${pack(allowed)}
];
`;

writeFileSync(join(here, '..', 'js', 'words.js'), out);
console.log(`wrote js/words.js: ${solutions.length} solutions, ${allowed.length} allowed`);
